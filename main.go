package main

import (
	"crypto/sha256"
	"encoding/hex"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"runtime"

	docsapp "github.com/odvcencio/gotreesitter-docs/app"
	_ "github.com/odvcencio/gotreesitter-docs/modules"
	"m31labs.dev/gosx"
	"m31labs.dev/gosx/env"
	"m31labs.dev/gosx/route"
	"m31labs.dev/gosx/server"
)

func main() {
	_, thisFile, _, _ := runtime.Caller(0)
	root := server.ResolveAppRoot(thisFile)
	if err := env.LoadDir(root, ""); err != nil {
		log.Fatal(err)
	}
	app, err := newApp(root)
	if err != nil {
		log.Fatal(err)
	}
	port := getenv("PORT", "8080")
	log.Printf("gotreesitter-docs at http://localhost:%s", port)
	log.Fatal(app.ListenAndServe(":" + port))
}

// newApp wires the router, middleware and mounts for root. Tests call it and
// serve app.Build() through httptest; main listens on it.
func newApp(root string) (*server.App, error) {
	docsapp.BindPublicAssetURL(func(path string) string {
		return versionedPublicAssetURL(root, path)
	})
	router := route.NewRouter()
	router.SetLayout(func(ctx *route.RouteContext, body gosx.Node) gosx.Node {
		ctx.AddHead(
			server.Font(server.FontProps{
				Family:  "Space Grotesk",
				Src:     docsapp.PublicAssetURL("fonts/space-grotesk-latin.woff2"),
				Type:    "font/woff2",
				Format:  "woff2",
				Weight:  "400 700",
				Display: "optional",
			}),
			server.Font(server.FontProps{
				Family:  "JetBrains Mono",
				Src:     docsapp.PublicAssetURL("fonts/jetbrains-mono-latin.woff2"),
				Type:    "font/woff2",
				Format:  "woff2",
				Weight:  "400 700",
				Display: "optional",
			}),
			server.Font(server.FontProps{
				Family:    "JetBrains Mono",
				Src:       docsapp.PublicAssetURL("fonts/jetbrains-mono-latin-italic.woff2"),
				Type:      "font/woff2",
				Format:    "woff2",
				Weight:    "400",
				Style:     "italic",
				Display:   "optional",
				NoPreload: true,
			}),
		)
		ctx.AddHead(server.Stylesheet(docsapp.PublicAssetURL("docs.css")))
		ctx.AddHead(gosx.El("link", gosx.Attrs(
			gosx.Attr("rel", "icon"),
			gosx.Attr("type", "image/svg+xml"),
			gosx.Attr("href", docsapp.PublicAssetURL("favicon.svg")),
		)))
		// Cloudflare Web Analytics (RUM) — cookieless, privacy-friendly beacon.
		// Loaded from the site head; the module script defers automatically.
		ctx.AddHead(gosx.El("script", gosx.Attrs(
			gosx.Attr("type", "module"),
			gosx.Attr("src", "https://static.cloudflareinsights.com/beacon.min.js"),
			gosx.Attr("data-cf-beacon", `{"token": "0282fc84c88d4a37820b398987f22b2d"}`),
		)))
		ctx.SetLanguage("en")
		return server.HTMLDocument(ctx.Document("gotreesitter", body))
	})

	if err := router.AddDir(filepath.Join(root, "app"), route.FileRoutesOptions{}); err != nil {
		return nil, err
	}

	app := server.New()
	app.EnableNavigation()
	app.Use(playgroundWASMCompression(root))
	router.SetRevalidator(app.Revalidator())
	app.EnableISR()
	app.SetPublicDir(filepath.Join(root, "public"))
	// A `gosx build` run stages the real WASM runtime + bootstrap JS the
	// islands need to hydrate into dist/ (build.json + assets/runtime/*);
	// without this, /gosx/wasm_exec.js and /gosx/runtime.wasm 404 and every
	// island stays server-HTML-only. dist/ is build output (gitignored,
	// regenerated by CI/deploy — see .gitignore), so this only takes effect
	// once that build has actually run; plain `go run .` in dev still falls
	// back to server's no-op bootstrap stub exactly as before.
	if info, err := os.Stat(filepath.Join(root, "dist", "build.json")); err == nil && !info.IsDir() {
		app.SetRuntimeRoot(filepath.Join(root, "dist"))
	}
	app.Redirect("GET /docs", "/docs/introduction", http.StatusTemporaryRedirect)
	app.API("GET /healthz", func(ctx *server.Context) (any, error) {
		ctx.NoStore()
		return map[string]any{
			"ok":      true,
			"product": "gotreesitter-docs",
			"version": docsapp.PlaygroundGTSVersion(),
		}, nil
	})
	rootHandler, err := router.BuildChecked()
	if err != nil {
		return nil, err
	}
	app.Mount("/", rootHandler)
	return app, nil
}

func getenv(key, fallback string) string {
	if value := os.Getenv(key); value != "" {
		return value
	}
	return fallback
}

func versionedPublicAssetURL(root, name string) string {
	base := server.AssetURL(name)
	payload, err := os.ReadFile(filepath.Join(root, "public", filepath.FromSlash(name)))
	if err != nil {
		return base
	}
	sum := sha256.Sum256(payload)
	return base + "?v=" + hex.EncodeToString(sum[:6])
}
